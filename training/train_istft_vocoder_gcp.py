class ConvTransposeISTFT(nn.Module):
    """
    Exact NOLA dual-window inverse STFT via a single fixed-buffer `ConvTranspose1d` (`n_fft == 4 * hop_length`).
    Achieves >138 dB SNR vs `torch.stft` with zero division, complex, or `STFT` ONNX ops.
    """

    def __init__(self, n_fft: int = 16, hop_length: int = 4) -> None:
        super().__init__()
        if n_fft != 4 * hop_length:
            raise ValueError(f"Expected n_fft == 4 * hop_length, got n_fft={n_fft}, hop_length={hop_length}")
        self.n_fft = n_fft
        self.hop_length = hop_length
        self.n_bins = n_fft // 2 + 1

        window = torch.hann_window(n_fft, periodic=True, dtype=torch.float64)
        dual_window = window / 1.5  # Exact NOLA dual window since sum_m w^2[n - m*H] == 1.5 identically

        n = torch.arange(n_fft, dtype=torch.float64).unsqueeze(0)
        k = torch.arange(self.n_bins, dtype=torch.float64).unsqueeze(1)
        scale = torch.full((self.n_bins, 1), 2.0 / n_fft, dtype=torch.float64)
        scale[0, 0] = 1.0 / n_fft
        scale[-1, 0] = 1.0 / n_fft

        angles = 2.0 * math.pi * k * n / n_fft
        basis_real = (scale * torch.cos(angles) * dual_window.unsqueeze(0)).to(torch.float32)
        basis_imag = (-scale * torch.sin(angles) * dual_window.unsqueeze(0)).to(torch.float32)
        basis = torch.cat([basis_real, basis_imag], dim=0).unsqueeze(1)  # [2*K, 1, N]
        self.register_buffer("basis", basis)
        self.register_buffer("analysis_window", window.to(torch.float32))

    def forward(self, mag: torch.Tensor, phase: torch.Tensor) -> torch.Tensor:
        real = mag * torch.cos(phase)
        imag = mag * torch.sin(phase)
        spec_cat = torch.cat([real, imag], dim=1)
        pad = (self.n_fft - self.hop_length) // 2
        return F.conv_transpose1d(spec_cat, self.basis, stride=self.hop_length, padding=pad)

    def target_magnitude(self, wav: torch.Tensor) -> torch.Tensor:
        """Compute exact matching sub-band STFT magnitude `[B, K, T_s]` for `wav` `[B, 1, H * T_s]`."""
        pad = (self.n_fft - self.hop_length) // 2
        y_pad = F.pad(wav.float(), (pad, pad), mode="reflect").squeeze(1)
        stft_c = torch.stft(
            y_pad,
            n_fft=self.n_fft,
            hop_length=self.hop_length,
            win_length=self.n_fft,
            window=self.analysis_window.float(),
            center=False,
            return_complex=True,
        )
        return torch.sqrt(stft_c.real.pow(2) + stft_c.imag.pow(2) + 1e-7)


class ISTFTWaveformDecoder(nn.Module):
    """
    Lightweight iSTFTNet vocoder drop-in replacement for `StudioVitsModel.waveform_decoder`.
    Input:  `z` `[B, 192, T]`
    Output: `wav` `[B, 1, 256 * T]`
    """

    def __init__(
        self,
        initial_channel: int = 192,
        resblock_kernel_sizes: tuple[int, ...] = (3, 7, 11),
        resblock_dilation_sizes: tuple[tuple[int, ...], ...] = ((1, 3, 5), (1, 3, 5), (1, 3, 5)),
        upsample_rates: tuple[int, ...] = (8, 8),
        upsample_initial_channel: int = 384,
        upsample_kernel_sizes: tuple[int, ...] = (16, 16),
        istft_n_fft: int = 16,
        istft_hop: int = 4,
    ) -> None:
        super().__init__()
        neural_up = 1
        for u in upsample_rates:
            neural_up *= u
        if neural_up * istft_hop != HOP_LENGTH:
            raise ValueError(f"Expected neural_up * istft_hop == {HOP_LENGTH}, got {neural_up} * {istft_hop}")

        self.num_kernels = len(resblock_kernel_sizes)
        self.num_upsamples = len(upsample_rates)
        self.istft_n_fft = istft_n_fft
        self.istft_hop = istft_hop
        self.n_bins = istft_n_fft // 2 + 1

        self.conv_pre = nn.utils.parametrizations.weight_norm(
            nn.Conv1d(initial_channel, upsample_initial_channel, 7, 1, padding=3)
        )
        self.ups = nn.ModuleList()
        for i, (u, k) in enumerate(zip(upsample_rates, upsample_kernel_sizes)):
            self.ups.append(
                nn.utils.parametrizations.weight_norm(
                    nn.ConvTranspose1d(
                        upsample_initial_channel // (2 ** i),
                        upsample_initial_channel // (2 ** (i + 1)),
                        k,
                        u,
                        padding=(k - u) // 2,
                    )
                )
            )

        self.resblocks = nn.ModuleList()
        for i in range(len(self.ups)):
            ch = upsample_initial_channel // (2 ** (i + 1))
            for k, d in zip(resblock_kernel_sizes, resblock_dilation_sizes):
                self.resblocks.append(ResBlock1(ch, k, tuple(d)))

        ch_final = upsample_initial_channel // (2 ** len(self.ups))
        self.conv_post = nn.utils.parametrizations.weight_norm(
            nn.Conv1d(ch_final, 2 * self.n_bins, 7, 1, padding=3)
        )
        self.istft = ConvTransposeISTFT(n_fft=istft_n_fft, hop_length=istft_hop)
        self._init_weights()

    def _init_weights(self) -> None:
        """Canonical HiFi-GAN / iSTFTNet N(0, 0.01) weight init + unsaturated initial log-magnitude bias."""
        with torch.no_grad():
            for m in self.modules():
                if isinstance(m, (nn.Conv1d, nn.ConvTranspose1d)):
                    if hasattr(m, "parametrizations") and "weight" in m.parametrizations:
                        orig1 = m.parametrizations.weight.original1
                        orig0 = m.parametrizations.weight.original0
                        orig1.normal_(0.0, 0.01)
                        norm_dims = tuple(range(1, orig1.ndim))
                        orig0.copy_(torch.linalg.vector_norm(orig1, dim=norm_dims, keepdim=True))
                    else:
                        m.weight.normal_(0.0, 0.01)
                    if m.bias is not None:
                        m.bias.zero_()
            if self.conv_post.bias is not None:
                # Start initial sub-band magnitude near exp(-2.0) ~= 0.135 so tanh() starts strictly linear (~0.08 RMS)
                self.conv_post.bias[: self.n_bins].fill_(-2.0)

    def strip_weight_norm(self) -> None:
        for module in self.modules():
            if hasattr(module, "parametrizations") and "weight" in module.parametrizations:
                torch.nn.utils.parametrize.remove_parametrizations(module, "weight", leave_parametrized=True)

    def forward_with_subband(self, x: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor]:
        x = self.conv_pre(x)
        for i in range(self.num_upsamples):
            x = F.leaky_relu(x, 0.1)
            x = self.ups[i](x)
            xs = self.resblocks[i * self.num_kernels](x)
            for j in range(1, self.num_kernels):
                xs = xs + self.resblocks[i * self.num_kernels + j](x)
            x = xs * (1.0 / self.num_kernels)
        x = F.leaky_relu(x)
        spec = self.conv_post(x)
        log_mag, phase_raw = torch.split(spec, [self.n_bins, self.n_bins], dim=1)
        mag = torch.exp(torch.clamp(log_mag, min=-11.0, max=7.0))
        phase = math.pi * torch.sin(phase_raw)
        wav = torch.tanh(self.istft(mag, phase))
        return wav, mag

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        wav, _ = self.forward_with_subband(x)
        return wav


class MultiResolutionSTFTLoss(nn.Module):
    """Multi-resolution spectral convergence + log-magnitude L1 loss at 24 kHz."""

    def __init__(
        self,
        fft_sizes: tuple[int, ...] = (512, 1024, 2048),
        hop_sizes: tuple[int, ...] = (128, 256, 512),
        win_lengths: tuple[int, ...] = (512, 1024, 2048),
    ) -> None:
        super().__init__()
        self.fft_sizes = fft_sizes
        self.hop_sizes = hop_sizes
        self.win_lengths = win_lengths
        for i, wl in enumerate(win_lengths):
            self.register_buffer(f"win_{i}", torch.hann_window(wl).float())

    def forward(self, y_real: torch.Tensor, y_hat: torch.Tensor) -> torch.Tensor:
        dev_type = y_real.device.type if y_real.device.type in ("cuda", "cpu") else "cpu"
        with torch.amp.autocast(device_type=dev_type, enabled=False):
            yr = y_real.squeeze(1).float()
            yh = y_hat.squeeze(1).float()
            tot = torch.zeros((), device=yr.device, dtype=torch.float32)
            for i, (n_fft, hop, wl) in enumerate(zip(self.fft_sizes, self.hop_sizes, self.win_lengths)):
                win = getattr(self, f"win_{i}").float()
                pad = (n_fft - hop) // 2
                yr_p = F.pad(yr.unsqueeze(1), (pad, pad), mode="reflect").squeeze(1)
                yh_p = F.pad(yh.unsqueeze(1), (pad, pad), mode="reflect").squeeze(1)
                sr = torch.stft(yr_p, n_fft, hop_length=hop, win_length=wl, window=win, center=False, return_complex=True)
                sh = torch.stft(yh_p, n_fft, hop_length=hop, win_length=wl, window=win, center=False, return_complex=True)
                mr = torch.sqrt(sr.real.pow(2) + sr.imag.pow(2) + 1e-7)
                mh = torch.sqrt(sh.real.pow(2) + sh.imag.pow(2) + 1e-7)
                sc_loss = torch.norm(mr - mh, p="fro") / (torch.norm(mr, p="fro") + 1e-7)
                mag_loss = F.l1_loss(torch.log(mr + 1e-5), torch.log(mh + 1e-5))
                tot = tot + sc_loss + mag_loss
            return tot / len(self.fft_sizes)


def warmstart_student_from_teacher(student: ISTFTWaveformDecoder, teacher: nn.Module) -> int:
    """
    Structured channel-consistent L2-importance warm-start from the 512-channel 24 kHz HiFi-GAN teacher
    into `student` (`384`, `448`, or `512` initial channels), preserving channel correspondence across
    `conv_pre -> ups[0] -> resblocks[0..2] -> ups[1] -> resblocks[3..5]` with variance-preserving
    `C_in_teacher / C_in_student` scaling and zero mutation of `teacher`'s weight_norm hooks.
    """
    t_w: dict[str, torch.Tensor] = {}
    t_b: dict[str, torch.Tensor] = {}
    with torch.no_grad():
        for name, mod in teacher.named_modules():
            if isinstance(mod, (nn.Conv1d, nn.ConvTranspose1d)):
                t_w[name] = mod.weight.detach().cpu().float().clone()
                if mod.bias is not None:
                    t_b[name] = mod.bias.detach().cpu().float().clone()

    if "conv_pre" not in t_w or "ups.0" not in t_w or "ups.1" not in t_w:
        return 0

    c0_t = int(t_w["conv_pre"].shape[0])  # 512
    c1_t = int(t_w["ups.0"].shape[1])     # 256
    c2_t = int(t_w["ups.1"].shape[1])     # 128

    c0 = int(student.conv_pre.out_channels)
    c1 = int(student.ups[0].out_channels)
    c2 = int(student.ups[1].out_channels)
    if c0 > c0_t or c1 > c1_t or c2 > c2_t:
        return 0

    def _set_conv(mod: nn.Module, w: torch.Tensor, b: torch.Tensor | None = None) -> None:
        if hasattr(mod, "parametrizations") and "weight" in mod.parametrizations:
            orig1 = mod.parametrizations.weight.original1
            orig0 = mod.parametrizations.weight.original0
            orig1.copy_(w.to(dtype=orig1.dtype, device=orig1.device))
            norm_dims = tuple(range(1, w.ndim))
            orig0.copy_(
                torch.linalg.vector_norm(w, dim=norm_dims, keepdim=True).to(dtype=orig0.dtype, device=orig0.device)
            )
        else:
            mod.weight.copy_(w.to(dtype=mod.weight.dtype, device=mod.weight.device))
        if b is not None and mod.bias is not None:
            mod.bias.copy_(b.to(dtype=mod.bias.dtype, device=mod.bias.device))

    copied = 0
    with torch.no_grad():
        imp0 = t_w["conv_pre"].norm(dim=(1, 2))
        idx0 = torch.topk(imp0, k=c0, largest=True).indices.sort().values

        imp1 = t_w["ups.0"][idx0].norm(dim=(0, 2))
        idx1 = torch.topk(imp1, k=c1, largest=True).indices.sort().values

        imp2 = t_w["ups.1"][idx1].norm(dim=(0, 2))
        idx2 = torch.topk(imp2, k=c2, largest=True).indices.sort().values

        _set_conv(student.conv_pre, t_w["conv_pre"][idx0], t_b.get("conv_pre", None)[idx0] if "conv_pre" in t_b else None)
        copied += 1

        if t_w["ups.0"].shape[2] == student.ups[0].weight.shape[2]:
            _set_conv(
                student.ups[0],
                t_w["ups.0"][idx0][:, idx1, :] * (float(c0_t) / float(c0)),
                t_b["ups.0"][idx1] if "ups.0" in t_b else None,
            )
            copied += 1

        for b_i in range(min(3, len(student.resblocks))):
            for c_list_name in ("convs1", "convs2"):
                c_list = getattr(student.resblocks[b_i], c_list_name)
                for l_i, conv in enumerate(c_list):
                    pf = f"resblocks.{b_i}.{c_list_name}.{l_i}"
                    if pf in t_w and t_w[pf].shape[2] == conv.weight.shape[2]:
                        _set_conv(
                            conv,
                            t_w[pf][idx1][:, idx1, :] * (float(c1_t) / float(c1)),
                            t_b[pf][idx1] if pf in t_b else None,
                        )
                        copied += 1

        if t_w["ups.1"].shape[2] == student.ups[1].weight.shape[2]:
            _set_conv(
                student.ups[1],
                t_w["ups.1"][idx1][:, idx2, :] * (float(c1_t) / float(c1)),
                t_b["ups.1"][idx2] if "ups.1" in t_b else None,
            )
            copied += 1
            for b_i in range(3, min(6, len(student.resblocks))):
                for c_list_name in ("convs1", "convs2"):
                    c_list = getattr(student.resblocks[b_i], c_list_name)
                    for l_i, conv in enumerate(c_list):
                        pf = f"resblocks.{b_i}.{c_list_name}.{l_i}"
                        if pf in t_w and t_w[pf].shape[2] == conv.weight.shape[2]:
                            _set_conv(
                                conv,
                                t_w[pf][idx2][:, idx2, :] * (float(c2_t) / float(c2)),
                                t_b[pf][idx2] if pf in t_b else None,
                            )
                            copied += 1
    return copied


def swap_vocoder_into_specialist_onnx(
    base_specialist_onnx: Path,
    student: ISTFTWaveformDecoder,
    out_specialist_onnx: Path,
) -> dict[str, Any]:
    """
    Export `student` (`ISTFTWaveformDecoder`) and surgically swap ONLY `/waveform_decoder/*`
    inside `base_specialist_onnx`, preserving `/waveform_decoder/conv_pre/Conv` and
    `/waveform_decoder/Tanh_output_0` so `splitStudioVitsOnnxBuffer` works untouched.
    """
    dec_export = ISTFTWaveformDecoder(
        initial_channel=int(student.conv_pre.in_channels),
        upsample_rates=tuple(int(m.stride[0]) for m in student.ups),
        upsample_initial_channel=int(student.conv_pre.out_channels),
        upsample_kernel_sizes=tuple(int(m.kernel_size[0]) for m in student.ups),
        istft_n_fft=student.istft_n_fft,
        istft_hop=student.istft_hop,
    ).cpu().eval()
    dec_export.load_state_dict({k: v.detach().cpu() for k, v in student.state_dict().items()})
    dec_export.strip_weight_norm()

    class _VocExportWrap(nn.Module):
        def __init__(self, d: nn.Module) -> None:
            super().__init__()
            self.waveform_decoder = d

        def forward(self, latent: torch.Tensor) -> torch.Tensor:
            return self.waveform_decoder(latent)

    tmp_fp32 = out_specialist_onnx.parent / f"_tmp_voc_{out_specialist_onnx.stem}_fp32.onnx"
    tmp_q8 = out_specialist_onnx.parent / f"_tmp_voc_{out_specialist_onnx.stem}_q8.onnx"
    out_specialist_onnx.parent.mkdir(parents=True, exist_ok=True)

    kw = {"dynamo": False} if "dynamo" in inspect.signature(torch.onnx.export).parameters else {}
    torch.onnx.export(
        _VocExportWrap(dec_export),
        (torch.zeros(1, 192, 112, dtype=torch.float32),),
        str(tmp_fp32),
        input_names=["latent"],
        output_names=["wav3d"],
        dynamic_axes={"latent": {2: "frames"}, "wav3d": {2: "samples"}},
        opset_version=17,
        do_constant_folding=True,
        **kw,
    )
    voc_q8_stats = compress_studio_vits_onnx(tmp_fp32, tmp_q8)
    base = onnx.load(str(base_specialist_onnx))
    voc_q = onnx.load(str(tmp_q8))
    tmp_fp32.unlink(missing_ok=True)
    tmp_q8.unlink(missing_ok=True)

    bg = base.graph
    conv_pre = next(
        n
        for n in bg.node
        if n.name == "/waveform_decoder/conv_pre/Conv" or n.name.endswith("waveform_decoder/conv_pre/Conv")
    )
    latent_tensor = conv_pre.input[0]
    dec_indices = [i for i, n in enumerate(bg.node) if n.name.startswith("/waveform_decoder")]
    orig_wav3d = bg.node[dec_indices[-1]].output[0]

    dec_weight_targets = set()
    for i in dec_indices:
        for inp in bg.node[i].input:
            if inp and inp != latent_tensor:
                dec_weight_targets.add(inp)

    other_consumers: dict[str, int] = {}
    for i, n in enumerate(bg.node):
        if i in set(dec_indices):
            continue
        for inp in n.input:
            if inp:
                other_consumers[inp] = other_consumers.get(inp, 0) + 1
    for out_info in bg.output:
        other_consumers[out_info.name] = other_consumers.get(out_info.name, 0) + 1

    remove_indices = set(dec_indices)
    changed = True
    while changed:
        changed = False
        for i, n in enumerate(bg.node):
            if i in remove_indices:
                continue
            if n.op_type in ("Cast", "Mul", "Constant") and len(n.output) == 1:
                out_t = n.output[0]
                if out_t in dec_weight_targets and other_consumers.get(out_t, 0) == 0:
                    remove_indices.add(i)
                    for inp in n.input:
                        if inp:
                            other_consumers[inp] = max(0, other_consumers.get(inp, 1) - 1)
                            dec_weight_targets.add(inp)
                    changed = True

    kept_nodes = [bg.node[i] for i in range(len(bg.node)) if i not in remove_indices]
    used_inputs = {inp for n in kept_nodes for inp in n.input if inp}
    kept_inits = [init for init in bg.initializer if init.name in used_inputs]

    vg = voc_q.graph
    voc_in_name = vg.input[0].name
    voc_out_name = vg.output[0].name

    init_rename: dict[str, str] = {}
    for init in vg.initializer:
        new_n = "istft_" + init.name
        init_rename[init.name] = new_n
        ni = onnx.TensorProto()
        ni.CopyFrom(init)
        ni.name = new_n
        kept_inits.append(ni)

    tensor_rename = dict(init_rename)
    tensor_rename[voc_in_name] = latent_tensor
    tensor_rename[voc_out_name] = orig_wav3d
    for n in vg.node:
        for out in n.output:
            if out and out not in tensor_rename:
                tensor_rename[out] = "istft_" + out

    voc_unpack_nodes = []
    voc_exec_nodes = []
    first_conv_seen = False
    for idx, n in enumerate(vg.node):
        nn_copy = onnx.NodeProto()
        nn_copy.CopyFrom(n)
        for i, inp in enumerate(nn_copy.input):
            if inp in tensor_rename:
                nn_copy.input[i] = tensor_rename[inp]
        for i, out in enumerate(nn_copy.output):
            if out in tensor_rename:
                nn_copy.output[i] = tensor_rename[out]

        if not first_conv_seen and nn_copy.op_type in ("Cast", "Mul") and latent_tensor not in nn_copy.input:
            nn_copy.name = f"istft_unpack_{idx}"
            voc_unpack_nodes.append(nn_copy)
        else:
            if not first_conv_seen and nn_copy.op_type == "Conv" and latent_tensor in nn_copy.input:
                nn_copy.name = "/waveform_decoder/conv_pre/Conv"
                first_conv_seen = True
            else:
                base_n = nn_copy.name.lstrip("/")
                if not base_n.startswith("waveform_decoder/"):
                    base_n = f"waveform_decoder/{base_n or (nn_copy.op_type + '_' + str(idx))}"
                nn_copy.name = "/" + base_n
            voc_exec_nodes.append(nn_copy)

    if not first_conv_seen:
        raise RuntimeError("Failed to find entry `/waveform_decoder/conv_pre/Conv` in student ONNX graph")

    insert_pos = next(i for i, n in enumerate(kept_nodes) if orig_wav3d in n.input)
    final_nodes = voc_unpack_nodes + kept_nodes[:insert_pos] + voc_exec_nodes + kept_nodes[insert_pos:]

    del bg.initializer[:]
    bg.initializer.extend(kept_inits)
    del bg.node[:]
    bg.node.extend(final_nodes)
    del bg.value_info[:]
    onnx.save(base, str(out_specialist_onnx))
    return {
        "vocoder_mb": voc_q8_stats["size_mb"],
        "specialist_mb": round(out_specialist_onnx.stat().st_size / (1024 * 1024), 2),
    }


def collect_transcripts_and_studio_utts(
    lang: str,
    gender: str,
    work_dir: Path,
    gcs_bucket: str | None,
    max_studio_utts: int = 2400,
    max_extra_texts: int = 2400,
    smoke_limit: int = 0,
) -> tuple[list[dict[str, Any]], list[str], list[dict[str, Any]]]:
    """
    Load held-out evaluation rows (`test_rows`) so zero transcript leakage occurs,
    plus `studio_utts` (24 kHz studio wav + transcript) and `extra_texts` for teacher synthesis.
    """
    eval_blacklist: set[str] = set()
    test_rows: list[dict[str, Any]] = []
    hf_tok = os.environ.get("HF_TOKEN") or None

    if not smoke_limit and gcs_bucket:
        eval_tar = work_dir / f"{lang}_eval.tar.gz"
        eval_blob_name = "en_indictts_eval.tar.gz" if lang == "en" else f"{lang}_eval.tar.gz"
        if gcs_download_if_exists(gcs_bucket, f"ninada_v5/eval_splits/{eval_blob_name}", eval_tar):
            ex_dir = work_dir / f"eval_ex_{lang}"
            ex_dir.mkdir(parents=True, exist_ok=True)
            with tarfile.open(eval_tar, "r:gz") as tf:
                tf.extractall(path=ex_dir)
            eval_tar.unlink(missing_ok=True)
            w_map = {p.name: p for p in ex_dir.rglob("*.wav")}
            for fn in ("val.jsonl", "test.jsonl"):
                fp = ex_dir / fn
                if not fp.exists():
                    continue
                for line in fp.read_text(encoding="utf-8").splitlines():
                    if not line.strip():
                        continue
                    r = json.loads(line)
                    eval_blacklist.add(f"{lang}:{clean_native_text(r['text'], lang)}")
                    if fn == "test.jsonl" and not (lang == "en" and gender == "Female"):
                        wn = Path(r["wav_path"]).name
                        if wn in w_map:
                            dst_dir = work_dir / "heldout_wavs"
                            dst_dir.mkdir(parents=True, exist_ok=True)
                            dst = dst_dir / wn
                            shutil.copy2(w_map[wn], dst)
                            r["local_wav"] = str(dst)
                            test_rows.append(r)
            shutil.rmtree(ex_dir, ignore_errors=True)

    target_studio = 8 if smoke_limit > 0 else max_studio_utts
    target_texts = 8 if smoke_limit > 0 else max_extra_texts
    need_carved_test = 4 if smoke_limit > 0 else (40 if len(test_rows) < 20 else 0)

    studio_utts: list[dict[str, Any]] = []
    extra_texts: list[str] = []
    seen_keys: set[str] = set()
    wav_dir = work_dir / "studio_24k" / f"{lang}_{gender.lower()}"
    wav_dir.mkdir(parents=True, exist_ok=True)

    def _unlink_hf_cached_file(p: str) -> None:
        try:
            if os.path.exists(p) and os.path.islink(p):
                rp = os.path.realpath(p)
                os.unlink(p)
                if os.path.exists(rp):
                    os.unlink(rp)
        except Exception:
            pass

    if lang == "en":
        # Stream 48,000 Hz -> 24,000 Hz single-speaker broadcast Studio Indian-English splits from SPRINGLab/IndicTTS-English
        shard_indices = [9, 8, 10] if gender == "Male" else [7, 8]
        shards = [f"data/train-{idx:05d}-of-00028.parquet" for idx in shard_indices]
        want_prefix = "train_hindifullmale_" if gender == "Male" else "train_hindifullfemale_"
        for shard in shards:
            if len(studio_utts) >= target_studio + need_carved_test and len(extra_texts) >= target_texts:
                break
            try:
                pq_path = hf_hub_download(
                    repo_id="SPRINGLab/IndicTTS-English", filename=shard, repo_type="dataset", token=hf_tok
                )
                pf = pq.ParquetFile(pq_path)
            except Exception as exc:
                print(f"[WARN] IndicTTS-English shard {shard} skipped: {exc}", flush=True)
                continue

            for batch in pf.iter_batches(batch_size=64):
                if len(studio_utts) >= target_studio + need_carved_test and len(extra_texts) >= target_texts:
                    break
                cols = batch.to_pydict()
                texts = cols.get("text", [])
                audio_col = cols.get("audio", [])
                for i, raw_t in enumerate(texts):
                    raw_str = str(raw_t or "")
                    if "\ufffd" in raw_str and not re.search(r"(?<=[A-Za-z])\ufffd(?=[sStTdDmMrRvVlL]\b)", raw_str):
                        continue
                    raw_text = _clean_indictts_english_transcript(raw_str)
                    if len(raw_text) < 10 or len(raw_text) > 260:
                        continue
                    norm_t = clean_native_text(raw_text, "en")
                    key = f"en:{norm_t}"
                    if len(norm_t) < 8 or key in eval_blacklist or key in seen_keys:
                        continue

                    aud = audio_col[i] if i < len(audio_col) else None
                    apath = str(aud.get("path") or "").strip().lower() if isinstance(aud, dict) else ""
                    if (
                        apath.startswith(want_prefix)
                        and len(studio_utts) < target_studio + need_carved_test
                        and isinstance(aud, dict)
                    ):
                        b_payload = aud.get("bytes")
                        if b_payload:
                            try:
                                raw_wav, orig_sr = sf.read(io.BytesIO(b_payload), dtype="float32")
                                wav_24k = (
                                    clean_studio_vits_24k(resample_to_24k(raw_wav, int(orig_sr)), pad_tail_sec=0.18)
                                    if (
                                        raw_wav.size > 0
                                        and int(orig_sr) >= 24000
                                        and float(np.max(np.abs(raw_wav))) < 0.998
                                    )
                                    else None
                                )
                            except Exception:
                                wav_24k = None
                            if wav_24k is not None:
                                dur_s = wav_24k.size / SAMPLE_RATE_24K
                                cps = len(norm_t) / max(dur_s, 0.1)
                                if 4.5 <= cps <= 25.0:
                                    seen_keys.add(key)
                                    uid = hashlib.sha1(f"{gender}:{key}".encode("utf-8")).hexdigest()[:12]
                                    wpath = wav_dir / f"en_{uid}.wav"
                                    sf.write(str(wpath), wav_24k, SAMPLE_RATE_24K, subtype="PCM_16")
                                    studio_utts.append(
                                        {
                                            "utt_id": f"en_{uid}",
                                            "lang": "en",
                                            "text": raw_text,
                                            "local_wav": str(wpath),
                                            "n_frames": wav_24k.size // HOP_LENGTH,
                                        }
                                    )
                                    continue
                    if len(extra_texts) < target_texts and (
                        apath.startswith("train_hindifullmale_") or apath.startswith("train_hindifullfemale_")
                    ):
                        seen_keys.add(key)
                        extra_texts.append(raw_text)
            _unlink_hf_cached_file(pq_path)
    else:
        api = HfApi(token=hf_tok)
        rasa_files = api.list_repo_files("ai4bharat/Rasa", repo_type="dataset")
        lang_dir = RASA_LANG_DIRS[lang]
        tr_shards = sorted(f for f in rasa_files if f.startswith(f"{lang_dir}/train-") and f.endswith(".parquet"))
        te_shards = sorted(f for f in rasa_files if f.startswith(f"{lang_dir}/test-") and f.endswith(".parquet"))
        for shard in interleave_from_ends(tr_shards) + interleave_from_ends(te_shards):
            if len(studio_utts) >= target_studio + need_carved_test and len(extra_texts) >= target_texts:
                break
            try:
                pq_path = hf_hub_download(repo_id="ai4bharat/Rasa", filename=shard, repo_type="dataset", token=hf_tok)
                pf = pq.ParquetFile(pq_path)
            except Exception:
                continue
            for batch in pf.iter_batches(batch_size=48):
                if len(studio_utts) >= target_studio + need_carved_test and len(extra_texts) >= target_texts:
                    break
                cols = batch.to_pydict()
                texts = cols.get("text", [])
                genders = cols.get("gender", [""] * len(texts))
                styles = cols.get("style", ["BOOK"] * len(texts))
                raw_bytes_col = cols.get("bytes")
                audio_struct_col = cols.get("audio")
                for i, raw_t in enumerate(texts):
                    raw_text = str(raw_t or "").strip()
                    if len(raw_text) < 8 or len(raw_text) > 260:
                        continue
                    norm_t = clean_native_text(raw_text, lang)
                    key = f"{lang}:{norm_t}"
                    if len(norm_t) < 6 or key in eval_blacklist or key in seen_keys:
                        continue
                    g_str = str(genders[i] or "").strip()
                    st = str(styles[i] or "").strip().upper()
                    if (
                        g_str == gender
                        and (not st or st in NEUTRAL_RASA_STYLES)
                        and len(studio_utts) < target_studio + need_carved_test
                    ):
                        b_payload = (
                            raw_bytes_col[i]
                            if (raw_bytes_col is not None and raw_bytes_col[i])
                            else (
                                audio_struct_col[i].get("bytes")
                                if (audio_struct_col is not None and isinstance(audio_struct_col[i], dict))
                                else None
                            )
                        )
                        if b_payload:
                            try:
                                raw_wav, orig_sr = sf.read(io.BytesIO(b_payload), dtype="float32")
                                wav_24k = clean_studio_vits_24k(resample_to_24k(raw_wav, int(orig_sr)))
                            except Exception:
                                wav_24k = None
                            if wav_24k is not None:
                                seen_keys.add(key)
                                uid = hashlib.sha1(f"{gender}:{key}".encode("utf-8")).hexdigest()[:12]
                                wpath = wav_dir / f"{lang}_{uid}.wav"
                                sf.write(str(wpath), wav_24k, SAMPLE_RATE_24K, subtype="PCM_16")
                                studio_utts.append(
                                    {
                                        "utt_id": f"{lang}_{uid}",
                                        "lang": lang,
                                        "text": raw_text,
                                        "local_wav": str(wpath),
                                        "n_frames": wav_24k.size // HOP_LENGTH,
                                    }
                                )
                                continue
                    if len(extra_texts) < target_texts:
                        seen_keys.add(key)
                        extra_texts.append(raw_text)
            _unlink_hf_cached_file(pq_path)

    if need_carved_test > 0 and len(studio_utts) > need_carved_test:
        carved = studio_utts[:need_carved_test]
        studio_utts = studio_utts[need_carved_test:]
        held_dir = work_dir / "heldout_wavs"
        held_dir.mkdir(parents=True, exist_ok=True)
        for r in carved:
            dst = held_dir / Path(r["local_wav"]).name
            if Path(r["local_wav"]).exists():
                shutil.copy2(r["local_wav"], dst)
                r["local_wav"] = str(dst)
        test_rows = carved

    return studio_utts, extra_texts, test_rows


@torch.no_grad()
def synthesize_teacher_pair_bank(
    teacher: StudioVitsModel,
    tok: StudioCharTokenizer,
    texts: list[str],
    studio_utts: list[dict[str, Any]],
    spec_ext: MultiSpecExtractor24k,
    device: torch.device,
    rng: random.Random,
    include_studio_posterior: bool = True,
) -> list[tuple[np.ndarray, np.ndarray]]:
    """
    Build an in-RAM bank of `(z_fp16 [192, T], wav_i16 [256*T])` pairs (~1 GB RAM for ~3,500 utterances):
      - Teacher inference pairs `(z_infer, y_teacher)` across varied `(noise_scale, length_scale)`
        so zero train-test latent mismatch exists with the frozen `prior + flow`!
      - Optional 25% studio posterior pairs `(z_post, y_studio)` for crisp 24 kHz harmonic detail.
    """
    teacher.eval()
    pairs: list[tuple[np.ndarray, np.ndarray]] = []
    use_bf16 = device.type == "cuda" and torch.cuda.is_bf16_supported()

    # 1. Inference-path teacher pairs `(z_infer, y_teacher)`
    all_texts = [u["text"] for u in studio_utts] + list(texts)
    rng.shuffle(all_texts)

    for txt in all_texts:
        ids = tok.text_to_ids(txt)
        if len(ids) < 6 or len(ids) > 480:
            continue
        x = torch.tensor([ids], dtype=torch.long, device=device)
        x_len = torch.tensor([len(ids)], dtype=torch.long, device=device)
        length_scale = rng.uniform(0.92, 1.08)
        noise_scale = rng.uniform(0.32, 0.667)
        noise_scale_dp = rng.choice([0.0, 0.35, 0.65])

        with torch.amp.autocast(device_type=device.type if device.type == "cuda" else "cpu", dtype=torch.bfloat16, enabled=use_bf16):
            enc_x, m_p, logs_p, x_mask = teacher.text_encoder(x, x_len)
            logw = teacher.duration_predictor(enc_x, x_mask, reverse=True, noise_scale=noise_scale_dp)
            w = torch.clamp_max(torch.exp(logw.float()), 50.0) * x_mask.float() * length_scale
            w_ceil = torch.ceil(w)
            w_ceil = torch.cat([w_ceil[:, :, :-1], torch.clamp_min(w_ceil[:, :, -1:], 8.0)], dim=2) * x_mask.float()
            y_lengths = torch.clamp_min(torch.sum(w_ceil, [1, 2]), 1).long()
            if int(y_lengths.item()) < 52:
                continue
            y_mask = sequence_mask(y_lengths, None).unsqueeze(1).to(x_mask.dtype)
            attn_mask = x_mask.transpose(1, 2) * y_mask
            attn = generate_path(w_ceil.squeeze(1), attn_mask)
            m_p_exp = torch.matmul(m_p.float(), attn.float())
            logs_p_exp = torch.matmul(logs_p.float(), attn.float())
            z_p = m_p_exp + torch.randn_like(m_p_exp) * torch.exp(logs_p_exp) * noise_scale
            z = teacher.flow(z_p.to(enc_x.dtype), y_mask, reverse=True).float() * y_mask.float()
            y_t = teacher.waveform_decoder(z.to(enc_x.dtype)).float().squeeze(0).squeeze(0)

        z_np = z.squeeze(0).cpu().numpy().astype(np.float16)
        y_np = np.clip(np.round(y_t.cpu().numpy() * 32767.0), -32767, 32767).astype(np.int16)
        pairs.append((z_np, y_np))

    # 2. Posterior-path studio pairs `(z_post, y_studio)` (~25% mix)
    if include_studio_posterior and studio_utts:
        n_post = max(1, len(pairs) // 3)
        sub_utts = list(studio_utts)
        rng.shuffle(sub_utts)
        for u in sub_utts[:n_post]:
            w_np, _ = sf.read(u["local_wav"], dtype="float32")
            nf = w_np.shape[0] // HOP_LENGTH
            if nf < 52:
                continue
            w_np = w_np[: nf * HOP_LENGTH]
            wav_t = torch.from_numpy(w_np).unsqueeze(0).to(device)
            spec = spec_ext.linear_spec(wav_t)
            nf_eff = min(nf, int(spec.size(2)))
            spec = spec[:, :, :nf_eff]
            w_np = w_np[: nf_eff * HOP_LENGTH]
            spec_len = torch.tensor([nf_eff], dtype=torch.long, device=device)
            z_post, _, _, y_mask = teacher.posterior_encoder(spec, spec_len)
            z_p_np = (z_post * y_mask).squeeze(0).float().cpu().numpy().astype(np.float16)
            y_s_np = np.clip(np.round(w_np * 32767.0), -32767, 32767).astype(np.int16)
            pairs.append((z_p_np, y_s_np))

    rng.shuffle(pairs)
    return pairs


def sample_vocoder_batch(
    pairs: list[tuple[np.ndarray, np.ndarray]],
    batch_size: int,
    seg_frames: int,
    rng: random.Random,
    device: torch.device,
) -> tuple[torch.Tensor, torch.Tensor]:
    seg_samples = seg_frames * HOP_LENGTH
    z_batch = np.empty((batch_size, 192, seg_frames), dtype=np.float32)
    y_batch = np.empty((batch_size, 1, seg_samples), dtype=np.float32)
    n_pool = len(pairs)
    for b in range(batch_size):
        z_fp16, y_i16 = pairs[rng.randrange(n_pool)]
        t_tot = z_fp16.shape[1]
        f0 = rng.randint(0, max(0, t_tot - seg_frames))
        z_batch[b] = z_fp16[:, f0 : f0 + seg_frames].astype(np.float32)
        s0 = f0 * HOP_LENGTH
        y_batch[b, 0] = y_i16[s0 : s0 + seg_samples].astype(np.float32) * (1.0 / 32767.0)
    return (
        torch.from_numpy(z_batch).to(device, non_blocking=True),
        torch.from_numpy(y_batch).to(device, non_blocking=True),
    )


@torch.no_grad()
def evaluate_student_vs_teacher(
    teacher: StudioVitsModel,
    student: ISTFTWaveformDecoder,
    tok: StudioCharTokenizer,
    test_rows: list[dict[str, Any]],
    device: torch.device,
) -> dict[str, Any]:
    """
    Objective quality evaluation on held-out `test_rows` directly against the current teacher voice
    (identical latent `z` fed to both `teacher.waveform_decoder` and `student`!).
    """
    teacher.eval()
    student.eval()
    mcds_vs_teacher: list[float] = []
    hfs_vs_teacher: list[float] = []
    f0s_vs_teacher: list[float] = []
    voiced_flags: list[float] = []
    mcds_vs_studio: list[float] = []

    for r in test_rows:
        ids = tok.text_to_ids(r["text"])
        if len(ids) < 5:
            continue
        x = torch.tensor([ids], dtype=torch.long, device=device)
        x_len = torch.tensor([len(ids)], dtype=torch.long, device=device)
        torch.manual_seed(42)
        enc_x, m_p, logs_p, x_mask = teacher.text_encoder(x, x_len)
        logw = teacher.duration_predictor(enc_x, x_mask, reverse=True, noise_scale=0.0)
        w = torch.clamp_max(torch.exp(logw), 50.0) * x_mask
        w_ceil = torch.ceil(w)
        w_ceil = torch.cat([w_ceil[:, :, :-1], torch.clamp_min(w_ceil[:, :, -1:], 8.0)], dim=2) * x_mask
        y_lengths = torch.clamp_min(torch.sum(w_ceil, [1, 2]), 1).long()
        y_mask = sequence_mask(y_lengths, None).unsqueeze(1).to(x_mask.dtype)
        attn = generate_path(w_ceil.squeeze(1), x_mask.transpose(1, 2) * y_mask)
        m_p_exp = torch.matmul(m_p, attn)
        logs_p_exp = torch.matmul(logs_p, attn)
        torch.manual_seed(42)
        z_p = m_p_exp + torch.randn_like(m_p_exp) * torch.exp(logs_p_exp) * 0.40
        z = teacher.flow(z_p, y_mask, reverse=True) * y_mask

        wav_teacher = teacher.waveform_decoder(z)[0, 0].detach().cpu().numpy().astype(np.float32)
        wav_student = student(z)[0, 0].detach().cpu().numpy().astype(np.float32)

        mcd_t, hf_t, f0_t, vok = compute_acoustic_metrics_24k(
            wav_teacher, wav_student, syn_sr=SAMPLE_RATE_24K
        )
        mcds_vs_teacher.append(mcd_t)
        hfs_vs_teacher.append(hf_t)
        f0s_vs_teacher.append(f0_t)
        voiced_flags.append(1.0 if vok else 0.0)

        if "local_wav" in r and os.path.exists(r["local_wav"]):
            gt_w, gt_sr = sf.read(r["local_wav"], dtype="float32")
            if gt_sr != SAMPLE_RATE_24K:
                gt_w = resample_to_24k(gt_w, int(gt_sr))
            mcd_s, _, _, _ = compute_acoustic_metrics_24k(gt_w, wav_student, syn_sr=SAMPLE_RATE_24K)
            mcds_vs_studio.append(mcd_s)

    student.train()
    return {
        "n_eval": len(mcds_vs_teacher),
        "vs_current_voice": {
            "mcd_db": bootstrap_ci(mcds_vs_teacher) if mcds_vs_teacher else {},
            "hf_8_12k_err_db": bootstrap_ci(hfs_vs_teacher) if hfs_vs_teacher else {},
            "f0_rmse_cents": bootstrap_ci(f0s_vs_teacher) if f0s_vs_teacher else {},
            "voiced_rate_pct": round(100.0 * float(np.mean(voiced_flags)), 2) if voiced_flags else 0.0,
        },
        "vs_studio_gt_mcd_db": bootstrap_ci(mcds_vs_studio) if mcds_vs_studio else {},
    }


def _levenshtein_distance(seq_a: list[str], seq_b: list[str]) -> int:
    if not seq_a:
        return len(seq_b)
    if not seq_b:
        return len(seq_a)
    prev = list(range(len(seq_b) + 1))
    for i, a in enumerate(seq_a, 1):
        curr = [i] + [0] * len(seq_b)
        for j, b in enumerate(seq_b, 1):
            cost = 0 if a == b else 1
            curr[j] = min(curr[j - 1] + 1, prev[j] + 1, prev[j - 1] + cost)
        prev = curr
    return prev[-1]


def _normalize_asr_text(s: str) -> str:
    import re

    s = s.lower().strip()
    s = re.sub(r"[^\w\s]", " ", s, flags=re.UNICODE)
    return re.sub(r"\s+", " ", s).strip()


@torch.no_grad()
def evaluate_whisper_asr(
    teacher: StudioVitsModel,
    student: ISTFTWaveformDecoder,
    tok: Any,
    test_rows: list[dict[str, Any]],
    lang: str,
    device: torch.device,
) -> dict[str, Any]:
    """Compare Whisper ASR WER/CER on held-out test sentences for teacher vs student."""
    try:
        import librosa
        from transformers import WhisperForConditionalGeneration, WhisperProcessor
    except Exception as exc:
        return {"skipped": str(exc)}

    whisper_lang_map = {
        "en": "english",
        "hi": "hindi",
        "bn": "bengali",
        "gu": "gujarati",
        "kn": "kannada",
        "ml": "malayalam",
        "mr": "marathi",
        "pa": "punjabi",
        "sa": "sanskrit",
        "ta": "tamil",
        "te": "telugu",
    }
    w_lang = whisper_lang_map.get(lang)
    model_id = "openai/whisper-small.en" if lang == "en" else "openai/whisper-small"
    try:
        proc = WhisperProcessor.from_pretrained(model_id)
        asr = WhisperForConditionalGeneration.from_pretrained(model_id).to(device).eval()
    except Exception as exc:
        return {"skipped": f"whisper load failed: {exc}"}

    student.eval()
    t_wer, s_wer, st_wer, t_cer, s_cer = [], [], [], [], []
    for r in test_rows:
        ids = tok.text_to_ids(r["text"])
        if len(ids) < 5:
            continue
        x = torch.tensor([ids], dtype=torch.long, device=device)
        x_len = torch.tensor([len(ids)], dtype=torch.long, device=device)
        torch.manual_seed(42)
        enc_x, m_p, logs_p, x_mask = teacher.text_encoder(x, x_len)
        logw = teacher.duration_predictor(enc_x, x_mask, reverse=True, noise_scale=0.0)
        w = torch.clamp_max(torch.exp(logw), 50.0) * x_mask
        w_ceil = torch.ceil(w)
        w_ceil = torch.cat([w_ceil[:, :, :-1], torch.clamp_min(w_ceil[:, :, -1:], 8.0)], dim=2) * x_mask
        y_lengths = torch.clamp_min(torch.sum(w_ceil, [1, 2]), 1).long()
        y_mask = sequence_mask(y_lengths, None).unsqueeze(1).to(x_mask.dtype)
        attn = generate_path(w_ceil.squeeze(1), x_mask.transpose(1, 2) * y_mask)
        torch.manual_seed(42)
        z_p = torch.matmul(m_p, attn) + torch.randn_like(torch.matmul(m_p, attn)) * torch.exp(torch.matmul(logs_p, attn)) * 0.40
        z = teacher.flow(z_p, y_mask, reverse=True) * y_mask

        wt_16k = librosa.resample(
            teacher.waveform_decoder(z)[0, 0].detach().cpu().numpy().astype(np.float32),
            orig_sr=SAMPLE_RATE_24K,
            target_sr=16000,
        )
        ws_16k = librosa.resample(
            student(z)[0, 0].detach().cpu().numpy().astype(np.float32),
            orig_sr=SAMPLE_RATE_24K,
            target_sr=16000,
        )
        gen_kw: dict[str, Any] = {}
        if lang != "en" and w_lang:
            gen_kw = {"language": w_lang, "task": "transcribe"}

        inp_t = proc(wt_16k, sampling_rate=16000, return_tensors="pt").input_features.to(device)
        inp_s = proc(ws_16k, sampling_rate=16000, return_tensors="pt").input_features.to(device)
        hyp_t = _normalize_asr_text(proc.batch_decode(asr.generate(inp_t, **gen_kw), skip_special_tokens=True)[0])
        hyp_s = _normalize_asr_text(proc.batch_decode(asr.generate(inp_s, **gen_kw), skip_special_tokens=True)[0])
        ref = _normalize_asr_text(r["text"])

        ref_w, ht_w, hs_w = ref.split(), hyp_t.split(), hyp_s.split()
        if ref_w:
            t_wer.append(100.0 * _levenshtein_distance(ref_w, ht_w) / len(ref_w))
            s_wer.append(100.0 * _levenshtein_distance(ref_w, hs_w) / len(ref_w))
        if ht_w:
            st_wer.append(100.0 * _levenshtein_distance(ht_w, hs_w) / len(ht_w))
        if ref:
            t_cer.append(100.0 * _levenshtein_distance(list(ref), list(hyp_t)) / len(ref))
            s_cer.append(100.0 * _levenshtein_distance(list(ref), list(hyp_s)) / len(ref))

    del asr
    if device.type == "cuda":
        torch.cuda.empty_cache()
    student.train()
    return {
        "model": model_id,
        "n_eval": len(t_wer),
        "current_voice_wer_pct": round(float(np.mean(t_wer)), 2) if t_wer else None,
        "istft_student_wer_pct": round(float(np.mean(s_wer)), 2) if s_wer else None,
        "student_vs_current_wer_pct": round(float(np.mean(st_wer)), 2) if st_wer else None,
        "current_voice_cer_pct": round(float(np.mean(t_cer)), 2) if t_cer else None,
        "istft_student_cer_pct": round(float(np.mean(s_cer)), 2) if s_cer else None,
    }


def train_voice_istft(
    lang: str,
    gender: str,
    arch: str,
    total_steps: int,
    batch_size: int,
    seg_frames: int,
    lr: float,
    work_dir: Path,
    out_dir: Path,
    gcs_bucket: str | None,
    gcs_prefix: str,
    save_every: int,
    refresh_pairs_every: int,
    disc_warmup_steps: int = 1500,
    smoke_steps: int = 0,
    local_base_onnx: Path | None = None,
    force_retrain: bool = False,
    eval_asr: bool = False,
) -> dict[str, Any]:
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    if device.type == "cuda":
        torch.backends.cudnn.benchmark = True
        torch.backends.cuda.matmul.allow_tf32 = True
        torch.backends.cudnn.allow_tf32 = True
    preset = STUDENT_ARCH_PRESETS[arch]
    voice_key = f"{lang}_{gender.lower()}"
    onnx_stem = lang if gender == "Male" else f"{lang}_female"

    if (
        not smoke_steps
        and not force_retrain
        and gcs_bucket
        and gcs_blob_exists(gcs_bucket, f"{gcs_prefix}/summary_{voice_key}_{arch}.json")
        and gcs_blob_exists(gcs_bucket, f"{gcs_prefix}/onnx/{onnx_stem}.onnx")
    ):
        print(f"[SKIP] {voice_key} ({arch}) already completed in gs://{gcs_bucket}/{gcs_prefix}/", flush=True)
        return {"voice": voice_key, "arch": arch, "skipped_completed": True}

    print(f"\n=== [ISTFT VOCODER] voice={voice_key} | arch={arch} | steps={total_steps} | device={device} ===", flush=True)

    recipe = SPECIALIST_RECIPES[lang]
    donor_repo = recipe["male_donor"] if gender == "Male" else recipe["female_donor"]
    donor_cfg, donor_sd = load_donor_checkpoint(donor_repo)

    if gender == "Male":
        tok, remapped_emb = build_target_tokenizer_and_remap_embeddings(
            lang, donor_cfg, donor_sd["text_encoder.emb.weight"]
        )
    else:
        m_cfg, m_sd = load_donor_checkpoint(recipe["male_donor"])
        tok, _ = build_target_tokenizer_and_remap_embeddings(lang, m_cfg, m_sd["text_encoder.emb.weight"])
        remapped_emb = remap_embeddings_to_existing_tokenizer(
            tok, donor_cfg, donor_sd["text_encoder.emb.weight"], lang
        )
        del m_sd

    teacher = StudioVitsModel(num_chars=tok.num_chars, use_discriminator=False)
    patched_sd = {k: v for k, v in donor_sd.items() if not k.startswith("disc.")}
    patched_sd["text_encoder.emb.weight"] = remapped_emb
    teacher.load_state_dict(patched_sd, strict=True)
    del donor_sd, patched_sd

    ckpt_teacher_path = work_dir / "teacher_ckpts" / f"{voice_key}.safetensors"
    if gcs_bucket and gcs_restore_v5_or_v4(gcs_bucket, f"checkpoints/{voice_key}.safetensors", ckpt_teacher_path):
        teacher.load_state_dict(load_file(str(ckpt_teacher_path)), strict=False)
        print(f"[TEACHER] Loaded trained specialist checkpoint {ckpt_teacher_path.name} from GCS", flush=True)

    base_onnx_path = work_dir / "base_onnx" / f"{onnx_stem}.onnx"
    if local_base_onnx and local_base_onnx.exists():
        base_onnx_path.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(local_base_onnx, base_onnx_path)
    elif gcs_bucket:
        gcs_restore_v5_or_v4(gcs_bucket, f"onnx/{onnx_stem}.onnx", base_onnx_path)

    teacher.to(device).eval()
    teacher.requires_grad_(False)

    student = ISTFTWaveformDecoder(**preset)
    n_ws = warmstart_student_from_teacher(student, teacher.waveform_decoder)
    print(
        f"[STUDENT] Initialized ISTFTWaveformDecoder({arch}); structured L2-warm-started {n_ws} conv layers from teacher",
        flush=True,
    )

    disc = VitsMultiPeriodDiscriminator(periods=(2, 3, 5, 7, 11))

    # Resume student + disc if an interrupted checkpoint exists in GCS
    student_ckpt_path = out_dir / "checkpoints" / f"{voice_key}_{arch}.pt"
    student_ckpt_path.parent.mkdir(parents=True, exist_ok=True)
    start_step = 0
    best_mcd = 999.0
    best_student_sd: dict[str, torch.Tensor] | None = None
    if not smoke_steps and not force_retrain and gcs_bucket:
        gcs_download_if_exists(gcs_bucket, f"{gcs_prefix}/checkpoints/{voice_key}_{arch}.pt", student_ckpt_path)

    student.to(device).train()
    disc.to(device).train()
    spec_ext = MultiSpecExtractor24k().to(device)
    mr_stft = MultiResolutionSTFTLoss().to(device)

    optim_g = torch.optim.AdamW(student.parameters(), lr=lr, betas=(0.8, 0.99), eps=1e-9, weight_decay=0.01)
    optim_d = torch.optim.AdamW(disc.parameters(), lr=lr, betas=(0.8, 0.99), eps=1e-9, weight_decay=0.01)

    if student_ckpt_path.exists() and not smoke_steps and not force_retrain:
        ck = torch.load(student_ckpt_path, map_location=device, weights_only=False)
        student.load_state_dict(ck["student"])
        disc.load_state_dict(ck["disc"])
        optim_g.load_state_dict(ck["optim_g"])
        optim_d.load_state_dict(ck["optim_d"])
        start_step = int(ck.get("step", 0))
        best_mcd = float(ck.get("best_mcd", 999.0))
        if "best_student" in ck and isinstance(ck["best_student"], dict):
            best_student_sd = {k: v.detach().cpu().clone() for k, v in ck["best_student"].items()}
        del ck
        print(f"[RESUME] Resumed {voice_key} student vocoder at step {start_step}/{total_steps} (best_mcd={best_mcd:.3f})", flush=True)

    sched_g = torch.optim.lr_scheduler.CosineAnnealingLR(
        optim_g, T_max=max(total_steps - start_step, 1), eta_min=lr * 0.15
    )
    sched_d = torch.optim.lr_scheduler.CosineAnnealingLR(
        optim_d, T_max=max(total_steps - start_step, 1), eta_min=lr * 0.15
    )

    use_studio_post = True
    studio_utts, extra_texts, test_rows = collect_transcripts_and_studio_utts(
        lang=lang,
        gender=gender,
        work_dir=work_dir,
        gcs_bucket=gcs_bucket,
        max_studio_utts=1600,
        max_extra_texts=2000,
        smoke_limit=8 if smoke_steps > 0 else 0,
    )
    rng = random.Random(20261104 + start_step)
    t_bank0 = time.perf_counter()
    pairs = synthesize_teacher_pair_bank(
        teacher=teacher,
        tok=tok,
        texts=extra_texts,
        studio_utts=studio_utts,
        spec_ext=spec_ext,
        device=device,
        rng=rng,
        include_studio_posterior=use_studio_post,
    )
    if refresh_pairs_every <= 0:
        shutil.rmtree(work_dir / "studio_24k" / voice_key, ignore_errors=True)
    tot_audio_hr = sum(y.shape[0] for _, y in pairs) / (SAMPLE_RATE_24K * 3600.0)
    print(
        f"[PAIR BANK] Built {len(pairs)} latent-audio pairs ({tot_audio_hr:.2f} hours) in {time.perf_counter()-t_bank0:.1f}s",
        flush=True,
    )

    use_bf16 = device.type == "cuda" and torch.cuda.is_bf16_supported()
    amp_dtype = torch.bfloat16 if use_bf16 else torch.float32
    dev_type = "cuda" if device.type == "cuda" else "cpu"

    running = {"mel": 0.0, "mrstft": 0.0, "sub": 0.0, "fm": 0.0, "adv": 0.0, "d": 0.0}
    n_log = 0
    t_loop0 = time.perf_counter()
    last_eval: dict[str, Any] = {}

    for step in range(start_step + 1, total_steps + 1):
        if refresh_pairs_every > 0 and step > start_step + 1 and (step % refresh_pairs_every == 0):
            pairs = synthesize_teacher_pair_bank(
                teacher=teacher,
                tok=tok,
                texts=extra_texts,
                studio_utts=studio_utts,
                spec_ext=spec_ext,
                device=device,
                rng=rng,
                include_studio_posterior=True,
            )

        z_seg, y_seg = sample_vocoder_batch(
            pairs=pairs, batch_size=batch_size, seg_frames=seg_frames, rng=rng, device=device
        )

        adv_active = step > disc_warmup_steps
        with torch.amp.autocast(device_type=dev_type, dtype=amp_dtype, enabled=use_bf16):
            y_hat, mag_hat = student.forward_with_subband(z_seg)
            if adv_active:
                y_d_rs, y_d_gs, _, _ = disc(y_seg, y_hat.detach())
                loss_d = discriminator_loss(y_d_rs, y_d_gs)
            else:
                loss_d = torch.zeros((), device=device)

        if adv_active and torch.isfinite(loss_d):
            optim_d.zero_grad(set_to_none=True)
            loss_d.backward()
            torch.nn.utils.clip_grad_norm_(disc.parameters(), 100.0)
            optim_d.step()

        with torch.amp.autocast(device_type=dev_type, dtype=amp_dtype, enabled=use_bf16):
            mel_r = spec_ext.wav_to_mel(y_seg.squeeze(1))
            mel_g = spec_ext.wav_to_mel(y_hat.squeeze(1))
            n_mf = min(mel_r.size(2), mel_g.size(2))
            loss_mel = F.l1_loss(mel_r[:, :, :n_mf], mel_g[:, :, :n_mf]) * 45.0
            loss_mr = mr_stft(y_seg, y_hat) * 2.5
            mag_r = student.istft.target_magnitude(y_seg)
            n_sb = min(mag_r.size(2), mag_hat.size(2))
            loss_sub = F.l1_loss(
                torch.log(mag_r[:, :, :n_sb] + 1e-5),
                torch.log(mag_hat.float()[:, :, :n_sb] + 1e-5),
            ) * 2.0
            if adv_active:
                _, y_d_gs_g, fmap_r, fmap_g = disc(y_seg, y_hat)
                loss_fm = feature_loss(fmap_r, fmap_g)
                loss_adv = generator_loss(y_d_gs_g)
            else:
                loss_fm = torch.zeros((), device=device)
                loss_adv = torch.zeros((), device=device)
            loss_g = loss_mel + loss_mr + loss_sub + loss_fm + loss_adv

        if torch.isfinite(loss_g):
            optim_g.zero_grad(set_to_none=True)
            loss_g.backward()
            torch.nn.utils.clip_grad_norm_(student.parameters(), 100.0)
            optim_g.step()

        sched_g.step()
        if adv_active:
            sched_d.step()

        running["mel"] += float((loss_mel.detach() / 45.0).item())
        running["mrstft"] += float((loss_mr.detach() / 2.5).item())
        running["sub"] += float((loss_sub.detach() / 2.0).item())
        running["fm"] += float(loss_fm.detach().item())
        running["adv"] += float(loss_adv.detach().item())
        running["d"] += float(loss_d.detach().item())
        n_log += 1

        if step % 200 == 0 or step == total_steps or smoke_steps > 0:
            elapsed = time.perf_counter() - t_loop0
            sps = (step - start_step) / max(elapsed, 1e-3)
            print(
                f"[{voice_key}:{arch}] step {step}/{total_steps} ({sps:.2f} it/s) | "
                f"mel={running['mel']/n_log:.4f} mrstft={running['mrstft']/n_log:.4f} "
                f"sub={running['sub']/n_log:.4f} fm={running['fm']/n_log:.3f} d={running['d']/n_log:.3f}",
                flush=True,
            )
            running = {k: 0.0 for k in running}
            n_log = 0

        if (save_every > 0 and step % save_every == 0) or step == total_steps:
            last_eval = evaluate_student_vs_teacher(teacher, student, tok, test_rows, device)
            cur_mcd = float(last_eval.get("vs_current_voice", {}).get("mcd_db", {}).get("mean", 999.0))
            print(
                f"[EVAL step={step}] vs_current_voice MCD={cur_mcd:.3f} dB | "
                f"F0={last_eval.get('vs_current_voice', {}).get('f0_rmse_cents', {}).get('mean', 0.0):.1f}c | "
                f"HF={last_eval.get('vs_current_voice', {}).get('hf_8_12k_err_db', {}).get('mean', 0.0):.2f} dB",
                flush=True,
            )
            is_new_best = (step > disc_warmup_steps or smoke_steps > 0) and (cur_mcd <= best_mcd)
            if is_new_best or best_student_sd is None:
                if is_new_best:
                    best_mcd = cur_mcd
                best_student_sd = {k: v.detach().cpu().contiguous().clone() for k, v in student.state_dict().items()}

            torch.save(
                {
                    "step": step,
                    "arch": arch,
                    "best_mcd": best_mcd,
                    "student": student.state_dict(),
                    "best_student": best_student_sd,
                    "disc": disc.state_dict(),
                    "optim_g": optim_g.state_dict(),
                    "optim_d": optim_d.state_dict(),
                    "eval": last_eval,
                },
                student_ckpt_path,
            )
            gcs_upload_if_configured(
                gcs_bucket, student_ckpt_path, f"{gcs_prefix}/checkpoints/{voice_key}_{arch}.pt"
            )

            if is_new_best or step == total_steps:
                export_student = ISTFTWaveformDecoder(**preset)
                export_student.load_state_dict(best_student_sd)
                export_student.eval()
                st_out = out_dir / "safetensors" / f"{voice_key}_{arch}.safetensors"
                st_out.parent.mkdir(parents=True, exist_ok=True)
                save_file(best_student_sd, str(st_out))
                gcs_upload_if_configured(
                    gcs_bucket, st_out, f"{gcs_prefix}/safetensors/{voice_key}_{arch}.safetensors"
                )
                if base_onnx_path.exists():
                    swapped_out = out_dir / "onnx" / f"{onnx_stem}.onnx"
                    swap_stats = swap_vocoder_into_specialist_onnx(base_onnx_path, export_student, swapped_out)
                    gcs_upload_if_configured(gcs_bucket, swapped_out, f"{gcs_prefix}/onnx/{onnx_stem}.onnx")
                    last_eval["onnx_swap"] = swap_stats

    if best_student_sd is not None:
        student.load_state_dict(best_student_sd)
    student.eval()

    final_eval = evaluate_student_vs_teacher(teacher, student, tok, test_rows, device)
    if not smoke_steps and (lang == "en" or eval_asr):
        asr_eval = evaluate_whisper_asr(teacher, student, tok, test_rows, lang, device)
        final_eval["whisper_asr"] = asr_eval
        print(f"[FINAL WHISPER ASR] {json.dumps(asr_eval)}", flush=True)
    if "onnx_swap" in last_eval:
        final_eval["onnx_swap"] = last_eval["onnx_swap"]

    # Save blind listening A/B WAV pairs (`teacher` vs `student` on identical `z`)
    ab_dir = out_dir / "ab_samples" / voice_key
    ab_dir.mkdir(parents=True, exist_ok=True)
    ab_manifest: list[dict[str, Any]] = []
    for idx, r in enumerate(test_rows[:12]):
        ids = tok.text_to_ids(r["text"])
        x = torch.tensor([ids], dtype=torch.long, device=device)
        x_len = torch.tensor([len(ids)], dtype=torch.long, device=device)
        with torch.no_grad():
            torch.manual_seed(100 + idx)
            enc_x, m_p, logs_p, x_mask = teacher.text_encoder(x, x_len)
            logw = teacher.duration_predictor(enc_x, x_mask, reverse=True, noise_scale=0.0)
            w = torch.clamp_max(torch.exp(logw), 50.0) * x_mask
            w_ceil = torch.ceil(w)
            w_ceil = torch.cat([w_ceil[:, :, :-1], torch.clamp_min(w_ceil[:, :, -1:], 8.0)], dim=2) * x_mask
            y_lengths = torch.clamp_min(torch.sum(w_ceil, [1, 2]), 1).long()
            y_mask = sequence_mask(y_lengths, None).unsqueeze(1).to(x_mask.dtype)
            attn = generate_path(w_ceil.squeeze(1), x_mask.transpose(1, 2) * y_mask)
            torch.manual_seed(100 + idx)
            z_p = torch.matmul(m_p, attn) + torch.randn_like(torch.matmul(m_p, attn)) * torch.exp(torch.matmul(logs_p, attn)) * 0.40
            z = teacher.flow(z_p, y_mask, reverse=True) * y_mask
            wt = teacher.waveform_decoder(z)[0, 0].cpu().numpy()
            ws = student(z)[0, 0].cpu().numpy()
        p_t = ab_dir / f"sample_{idx:02d}_current.wav"
        p_s = ab_dir / f"sample_{idx:02d}_istft.wav"
        sf.write(str(p_t), wt, SAMPLE_RATE_24K, subtype="PCM_16")
        sf.write(str(p_s), ws, SAMPLE_RATE_24K, subtype="PCM_16")
        gcs_upload_if_configured(gcs_bucket, p_t, f"{gcs_prefix}/ab_samples/{voice_key}/{p_t.name}")
        gcs_upload_if_configured(gcs_bucket, p_s, f"{gcs_prefix}/ab_samples/{voice_key}/{p_s.name}")
        ab_manifest.append(
            {
                "index": idx,
                "text": r["text"],
                "duration_sec": round(len(ws) / SAMPLE_RATE_24K, 2),
                "current_wav": p_t.name,
                "istft_wav": p_s.name,
            }
        )
    ab_man_path = ab_dir / "manifest.json"
    ab_man_path.write_text(json.dumps(ab_manifest, indent=2) + "\n", encoding="utf-8")
    gcs_upload_if_configured(gcs_bucket, ab_man_path, f"{gcs_prefix}/ab_samples/{voice_key}/manifest.json")

    summary = {
        "voice": voice_key,
        "arch": arch,
        "steps": total_steps,
        "wall_sec": round(time.perf_counter() - t_loop0, 2),
        "best_mcd_vs_current_db": round(best_mcd, 3),
        "final_eval": final_eval,
    }
    sum_path = out_dir / f"summary_{voice_key}_{arch}.json"
    sum_path.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    gcs_upload_if_configured(gcs_bucket, sum_path, f"{gcs_prefix}/summary_{voice_key}_{arch}.json")

    # Reclaim /tmp and VRAM between sequential voices on Cloud Run
    del pairs, teacher, student, disc, optim_g, optim_d
    student_ckpt_path.unlink(missing_ok=True)
    ckpt_teacher_path.unlink(missing_ok=True)
    base_onnx_path.unlink(missing_ok=True)
    shutil.rmtree(work_dir / "heldout_wavs", ignore_errors=True)
    shutil.rmtree(work_dir / "studio_24k" / voice_key, ignore_errors=True)
    if os.environ.get("CLEAN_HF_CACHE", "0").strip() == "1":
        hf_hub_cache = Path.home() / ".cache" / "huggingface" / "hub"
        for d in hf_hub_cache.glob("models--SYSPIN--*"):
            shutil.rmtree(d, ignore_errors=True)
        for d in hf_hub_cache.glob("datasets--*"):
            shutil.rmtree(d, ignore_errors=True)
    gc.collect()
    if device.type == "cuda":
        torch.cuda.empty_cache()
    return summary


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--voices", type=str, default="en:male", help="Comma-separated lang:gender pairs (e.g. 'en:male')")
    parser.add_argument("--arch", type=str, default="c8c8_384", choices=list(STUDENT_ARCH_PRESETS.keys()))
    parser.add_argument("--steps", type=int, default=35000)
    parser.add_argument("--batch-size", type=int, default=24)
    parser.add_argument("--seg-frames", type=int, default=48)
    parser.add_argument("--lr", type=float, default=2.0e-4)
    parser.add_argument("--disc-warmup-steps", type=int, default=1500)
    parser.add_argument("--save-every", type=int, default=5000)
    parser.add_argument("--refresh-pairs-every", type=int, default=0)
    parser.add_argument("--work-dir", type=Path, default=Path("/tmp/ninada_istft_work"))
    parser.add_argument("--out-dir", type=Path, default=Path("/tmp/ninada_istft_out"))
    parser.add_argument("--gcs-bucket", type=str, default="")
    parser.add_argument("--gcs-prefix", type=str, default="ninada_istft_v2")
    parser.add_argument("--smoke-steps", type=int, default=0)
    parser.add_argument("--local-base-onnx", type=Path, default=None)
    parser.add_argument("--force", action="store_true", help="Ignore existing completed checkpoint in gcs-prefix")
    parser.add_argument("--eval-asr", action="store_true", help="Also run Whisper ASR eval on non-English voices")
    args = parser.parse_args()

    args.work_dir.mkdir(parents=True, exist_ok=True)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    gcs_bucket = args.gcs_bucket.strip() or None

    all_summaries = {}
    for spec in [s.strip() for s in args.voices.split(",") if s.strip()]:
        parts = spec.split(":")
        lang = parts[0].lower()
        gender = "Female" if (len(parts) > 1 and parts[1].lower().startswith("f")) else "Male"
        steps_eff = args.smoke_steps if args.smoke_steps > 0 else args.steps
        bs_eff = 2 if args.smoke_steps > 0 else args.batch_size
        dw_eff = 1 if args.smoke_steps > 0 else args.disc_warmup_steps
        all_summaries[f"{lang}_{gender.lower()}"] = train_voice_istft(
            lang=lang,
            gender=gender,
            arch=args.arch,
            total_steps=steps_eff,
            batch_size=bs_eff,
            seg_frames=args.seg_frames,
            lr=args.lr,
            work_dir=args.work_dir,
            out_dir=args.out_dir,
            gcs_bucket=gcs_bucket,
            gcs_prefix=args.gcs_prefix,
            save_every=args.save_every,
            refresh_pairs_every=args.refresh_pairs_every,
            disc_warmup_steps=dw_eff,
            smoke_steps=args.smoke_steps,
            local_base_onnx=args.local_base_onnx,
            force_retrain=args.force,
            eval_asr=args.eval_asr,
        )
    print("\n=== ALL REQUESTED ISTFT VOCODER RUNS COMPLETE ===", flush=True)
    print(json.dumps(all_summaries, indent=2), flush=True)


if __name__ == "__main__":
    main()
